// Defects 22 and 24: a text dictionary's `_value` literal grammar cannot spell
// every value, and the writer acted as though it could.
//
// Two kinds of value have no literal form: rank >= 3 of any class (defect 22), and
// complex at ANY rank (defect 24). Both go out as a `{"_type": "cdata"}` uuencoded
// MAT byte stream, which is what MATLAB itself writes for them.
//
// The literal `Matrix(2,3,2)\n[[...]]` this used to emit is not merely unusual —
// MATLAB READS every candidate rank-3 spelling back as an empty 1x0 or the scalar
// 0 (test/parity/matlab/probe_rank3_serial.m), so every save of an N-D value
// destroyed it. What MATLAB itself writes for a rank >= 3 value, of EVERY class, is
// a `{"_type": "cdata"}` uuencoded MAT byte stream (probe_nd_rich.m), placed at the
// leaf wherever the value sits — entry value, object property, struct field, cell
// element, two levels down — with every container above it in its ordinary JSON
// form (probe_nd_nested.m).
//
// So the assertions here are against MATLAB's own bytes and MATLAB's own JSON:
//
//   * fixtures/nd_rich.sldd     — thirteen kinds at rank 3, one entry each. Our
//                                 writer must reproduce each cdata string exactly.
//   * fixtures/nd_nested.sldd   — the same value nested six ways. Our serialization
//                                 must equal MATLAB's whole value object.
//   * artifacts/text/cases.sldd — the three rank-3 entries, EDITED, because a form
//                                 that only round-trips untouched values is worth
//                                 nothing to a consumer that writes.
//
// Both fixtures were written by MATLAB and are read here as ground truth, never
// regenerated by us.
//
// MATLAB was also asked directly, which is the only acceptance criterion that
// matters: every entry below was spliced into MATLAB's own dictionary and reopened
// with Simulink.data.dictionary.open. Fifty-four cases — thirteen ND kinds, six
// placements, nine typed/char shapes, six char shapes, seven char retypes, two
// complex, three entry edits, three Parameter edits, five grammar literals — all read
// back isequal, same class, same size, with the edits in the right cell:
// `WRITEBACK FAILURES 0 of 54` (see probe_writeback.mjs / probe_writeback.m).
