rows = struct('id', {}, 'expr', {}, 'accepted', {}, 'identifier', {}, ...
              'message', {}, 'storedClass', {}, 'storedSize', {});
for k = 1:size(cases, 1)
    r = struct('id', cases{k,1}, 'expr', cases{k,2}, 'accepted', false, ...
               'identifier', '', 'message', '', 'storedClass', '', 'storedSize', []);
    p = Simulink.Parameter;
    try
        v = eval(cases{k,2});           % building the value is not the question...
    catch e
        r.identifier = ['BUILD:' e.identifier]; r.message = e.message;   % e.g. no fi license
        rows(end+1) = r; %#ok<AGROW>
        continue
    end
    try
        p.Value = v;                    % ...assigning it is
        r.accepted = true;
        r.storedClass = class(p.Value);
        r.storedSize = size(p.Value);
    catch e
        r.identifier = e.identifier; r.message = e.message;
    end
    rows(end+1) = r; %#ok<AGROW>
    fprintf('  %-22s accepted=%d %s\n', r.id, r.accepted, r.identifier);
end

