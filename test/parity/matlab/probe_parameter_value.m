    'field_string_scalar',   'struct(''a'', "abc")'; ...
    'field_string_array',    'struct(''a'', ["a" "b"])'; ...
    'field_string_column',   'struct(''a'', ["ab"; "cd"])'; ...
    'field_cell',            'struct(''a'', {{1, 2}})'; ...
    'field_empty_cell',      'struct(''a'', {{}})'; ...
    'field_logical',         'struct(''a'', true)'; ...
    'field_logical_array',   'struct(''a'', [true false])'; ...
    'field_int8',            'struct(''a'', int8(5))'; ...
    'field_single',          'struct(''a'', single(1.5))'; ...
    'field_complex',         'struct(''a'', 1+2i)'; ...
    'field_nan',             'struct(''a'', NaN)'; ...
    'field_matrix',          'struct(''a'', [1 2; 3 4])'; ...
    'field_nd',              'struct(''a'', ones(2,2,2))'; ...
    'field_sparse',          'struct(''a'', sparse(1))'; ...
    'field_enum',            'struct(''a'', matlab.lang.OnOffSwitchState.on)'; ...
    'field_fi',              'struct(''a'', fi(1.5))'; ...
    'field_nested_ok',       'struct(''a'', struct(''b'', 1))'; ...
    'field_nested_empty',    'struct(''a'', struct(''b'', []))'; ...
    'field_nested_char',     'struct(''a'', struct(''b'', ''x''))'; ...
    'field_nested_string',   'struct(''a'', struct(''b'', "x"))'; ...
