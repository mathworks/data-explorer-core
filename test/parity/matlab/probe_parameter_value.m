srows = struct('id', {}, 'base', {}, 'edit', {}, 'baseAccepted', {}, 'accepted', {}, ...
               'identifier', {}, 'message', {}, 'storedClass', {}, 'storedSize', {}, ...
               'inPlaceAccepted', {}, 'inPlaceIdentifier', {});
for k = 1:size(structural, 1)
    r = struct('id', structural{k,1}, 'base', structural{k,2}, 'edit', structural{k,3}, ...
               'baseAccepted', false, 'accepted', false, 'identifier', '', 'message', '', ...
               'storedClass', '', 'storedSize', [], 'inPlaceAccepted', false, 'inPlaceIdentifier', '');
    base = eval(structural{k,2});
    p = Simulink.Parameter;
    try
        p.Value = base;
        r.baseAccepted = true;
    catch e
        r.identifier = ['BASE:' e.identifier]; r.message = e.message;
        srows(end+1) = r; %#ok<AGROW>
        continue
    end
    X = base; %#ok<NASGU>
    eval(structural{k,3});              % the edit, on a plain value
    q = Simulink.Parameter;
    try
        q.Value = X;                    % ...and the Value it leaves
        r.accepted = true;
        r.storedClass = class(q.Value);
        r.storedSize = size(q.Value);
    catch e
        r.identifier = e.identifier; r.message = e.message;
    end
    try
        eval(strrep(structural{k,3}, 'X', 'p.Value'));   % the same edit, in place
        r.inPlaceAccepted = true;
    catch e
        r.inPlaceIdentifier = e.identifier;
    end
    srows(end+1) = r; %#ok<AGROW>
    fprintf('  %-28s accepted=%d inPlace=%d %s\n', r.id, r.accepted, r.inPlaceAccepted, r.identifier);
end

