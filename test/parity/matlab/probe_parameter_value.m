% What does MATLAB accept as a Simulink.Parameter Value -- at the top level, and as
% a field of a struct Value?  (C-160 / C-042, ruled 2026-10-15: core mirrors MATLAB's
% edit-time check, and a Parameter's struct Value obeys the Parameter's rules, not a
% plain struct variable's.)
%
% Why this exists: core had exactly two measurements -- `p.Value = struct('a',[])`
% raises "A valid structure must be numeric" (Simulink.Parameter.md), and
% `p.Value = ["ab"; "cd"]` raises Simulink:Data:Param_Invalid_Value (DESIGN.md).
% MATLAB's own message names the allowed kinds ("a numeric array, fi object,
% enumerated value, structure whose fields contain valid values, string scalar, or
% an expression"), but not where a field's rule differs from the top level's: is a
% char field valid? an empty char? a logical? a nested struct with an empty field?
% Core must mirror the answer exactly, so it is asked of MATLAB, not inferred.
%
% The cases cover every value the Value editor can produce from typed text
% (MatlabValueParser: numbers, matrices, logicals, char, string, string arrays,
% cells, complex scalars, and [] / '' / "" / {}), at the top level and as a field,
% plus kinds only a file can hold (int8, single, sparse, N-D, enum, fi, nested and
% arrayed structs) so the field rule is pinned beyond what is typeable today.
%
% STRUCTURAL edits (the ruling A2, 2026-10-15 evening: "Removing or adding a field or an
% element inside a Simulink.Parameter's Value is refused where MATLAB refuses the resulting
% Value"). Each `structural` row starts from a Value MATLAB accepts (`base`) and makes one
% edit the tree can make, written with X for the Value: remove a field (rmfield), add one
% (the tree adds `field`, holding 0), remove an element of an array (X.c(2) = []) or add one
% (the tree appends a 0 of the array's class). The edited value is assigned to a new
% Parameter (`accepted`, ...), and the same edit is also made in place on a Parameter holding
% `base` (X is p.Value: `inPlaceAccepted`, `inPlaceIdentifier`), to show the two agree.
%
% Run: env PARAM_VALUE_OUT=/tmp/paramvalue mw -using Bmain matlab -nodesktop \
%          -batch "run('$PWD/test/parity/matlab/probe_parameter_value.m')"
% then: cp /tmp/paramvalue/parameter_value_truth.json test/fixtures/
% Output: parameter_value_truth.json, {version, release, cases, structural}, one case per row:
%   cases:      id, expr, accepted, identifier, message, storedClass, storedSize;
%   structural: id, base, edit, baseAccepted, accepted, identifier, message, storedClass,
%               storedSize, inPlaceAccepted, inPlaceIdentifier.

